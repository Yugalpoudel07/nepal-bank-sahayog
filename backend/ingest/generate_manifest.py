"""
generate_manifest.py
====================
Write data/raw/manifest.yaml from the NRB catalog (data/catalog/nrb_core_catalog.json),
inferring family, institutions, directive edition and circular number from each title.

Files you added yourself (not in the catalog) get guessed entries. Entries already in
manifest.yaml that you edited by hand are kept unless you pass --overwrite.

Usage (from backend/):
    python -m ingest.generate_manifest
    python -m ingest.generate_manifest --overwrite
"""

from __future__ import annotations

import argparse
import json
import logging
import urllib.parse
from pathlib import Path

import yaml

from app.config import get_settings
from app.logging_setup import setup_logging
from ingest.manifest_tools import ManifestEntry, discover_files, guess_entry

log = logging.getLogger("generate_manifest")
NRB_UPLOADS = "https://www.nrb.org.np/contents/uploads/"
CATALOG = Path(__file__).resolve().parent.parent / "data" / "catalog" / "nrb_core_catalog.json"

HEADER = """\
# Corpus manifest, generated by `python -m ingest.generate_manifest` from the NRB catalog.
# Fields: see ingest/manifest_tools.py. Edit freely; your edits are kept on regeneration
# (unless --overwrite). family/institutions/base_year/circular_no were inferred from the titles.
"""
FIELDS = ("path", "doc_type", "title", "language", "fiscal_year", "family", "institutions", "base_year",
          "circular_no", "published", "issue_date_bs", "source_url", "ocr")


def catalog_entries(catalog: Path = CATALOG) -> list[ManifestEntry]:
    """Manifest entries for every catalog row: [local_path, doc_type, fy, lang, title, nrb_path, bytes]."""
    rows = json.loads(catalog.read_text(encoding="utf-8"))
    out = []
    for local, doc_type, fy, lang, title, rel, _size in rows:
        out.append(ManifestEntry(
            path=local, doc_type=doc_type, title=title, language=lang, fiscal_year=fy,
            published="-".join(rel.split("/")[:2]), source_url=NRB_UPLOADS + urllib.parse.quote(rel),
        ))
    return out


def entry_dict(e: ManifestEntry) -> dict:
    d = e.model_dump()
    return {k: d[k] for k in FIELDS if d.get(k) not in (None, [])}


def build(raw_dir: Path, overwrite: bool = False) -> Path:
    manifest = raw_dir / "manifest.yaml"
    existing: dict[str, dict] = {}
    if manifest.exists() and not overwrite:
        data = yaml.safe_load(manifest.read_text(encoding="utf-8")) or {}
        for item in data.get("documents", []) or []:
            if "path" in item and "present" not in item:  # hand-maintained entries only
                existing[item["path"]] = item

    entries = {e.path: e for e in catalog_entries()}
    for f in discover_files(raw_dir):
        rel = f.relative_to(raw_dir).as_posix()
        if rel not in entries:
            entries[rel] = guess_entry(raw_dir, f)
    docs = [existing.get(p) or entry_dict(e) for p, e in sorted(entries.items())]
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(HEADER + yaml.safe_dump({"documents": docs}, allow_unicode=True, sort_keys=False,
                                                width=200), encoding="utf-8")
    log.info("manifest written", extra={"kv": {"path": str(manifest), "documents": len(docs)}})
    return manifest


def main() -> None:
    setup_logging()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--overwrite", action="store_true", help="ignore hand edits in the existing manifest")
    args = ap.parse_args()
    build(get_settings().raw_dir, overwrite=args.overwrite)


if __name__ == "__main__":
    main()
